// A small .app per library item in ~/Applications/OverPass, so games show up in Launchpad, Spotlight
// and the Dock like native apps. The wrapper only holds a script that hands off to `OverPass --launch`,
// so bottle settings changed later still apply.
enum AppWrappers {
    static let enabledKey = "createAppWrappers"
    private static let bottleKey = "OverPassBottle"
    private static let programKey = "OverPassProgram"
    /// What the icon was drawn with; a change redraws it.
    private static let iconKey = "OverPassIcon"
    private static let queue = DispatchQueue(label: "OverPass.AppWrappers")
    /// Off in launch mode: exec would cut a background sync off halfway through writing a wrapper.
    nonisolated(unsafe) static var syncAllowed = true

    static var directory: URL {
        FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Applications/OverPass")
    }

    static var isEnabled: Bool {
        UserDefaults.standard.object(forKey: enabledKey) as? Bool ?? true
    }

    /// Creates, updates and removes wrappers to match the library. Runs in the background; cheap when nothing changed.
    static func sync(_ library: [LibraryItem]) {
        // Only an installed app bundle has a stable path for wrappers to call; `swift run` builds don't.
        guard syncAllowed, let executable = Bundle.main.executablePath, Bundle.main.bundleURL.pathExtension == "app" else { return }
        let items = isEnabled ? library : []
        queue.async { syncNow(items, overpass: executable) }
    }

    private static func syncNow(_ items: [LibraryItem], overpass: String) {
        let fm = FileManager.default
        // Same game name in two bottles: tell them apart by bottle.
        let counts = Dictionary(items.map { ($0.app.name.lowercased(), 1) }, uniquingKeysWith: +)
        var wanted: [String: LibraryItem] = [:]
        for item in items {
            let base = counts[item.app.name.lowercased()]! > 1 ? "\(item.app.name) (\(item.bottle.name))" : item.app.name
            wanted[sanitize(base) + ".app"] = item
        }

        let existing = (try? fm.contentsOfDirectory(atPath: directory.path)) ?? []
        for name in existing where name.hasSuffix(".app") && wanted[name] == nil {
            let app = directory.appendingPathComponent(name)
            // Never touch apps someone else put here.
            if ownedWrapper(app) { try? fm.removeItem(at: app) }
        }
        if !wanted.isEmpty { try? fm.createDirectory(at: directory, withIntermediateDirectories: true) }
        for (name, item) in wanted {
            let app = directory.appendingPathComponent(name)
            if fm.fileExists(atPath: app.path) && !ownedWrapper(app) { continue }
            try? write(item, to: app, overpass: overpass)
        }
        if fm.fileExists(atPath: directory.path), (try? fm.contentsOfDirectory(atPath: directory.path))?.isEmpty == true {
            try? fm.removeItem(at: directory)
        }
    }

    private static func ownedWrapper(_ app: URL) -> Bool {
        let plist = NSDictionary(contentsOf: app.appendingPathComponent("Contents/Info.plist"))
        return plist?[bottleKey] != nil
    }

    private static func write(_ item: LibraryItem, to app: URL, overpass: String) throws {
        let fm = FileManager.default
        let contents = app.appendingPathComponent("Contents")
        let script = contents.appendingPathComponent("MacOS/launch")
        let icns = contents.appendingPathComponent("Resources/AppIcon.icns")

        let scriptText = """
        #!/bin/sh
        # Generated by OverPass; rewritten whenever OverPass starts.
        OVERPASS=\(shellQuote(overpass))
        [ -x "$OVERPASS" ] || exec open -b no.arctim.overpass
        exec "$OVERPASS" --launch \(([item.bottle.path.path, item.app.executable] + item.app.arguments).map(shellQuote).joined(separator: " "))

        """
        var plist: [String: Any] = [
            "CFBundleExecutable": "launch",
            "CFBundleIdentifier": "no.arctim.overpass.game." + WindowsIcons.stableHash(item.id),
            "CFBundleName": item.app.name,
            "CFBundleDisplayName": item.app.name,
            "CFBundlePackageType": "APPL",
            "CFBundleIconFile": "AppIcon",
            "CFBundleShortVersionString": "1.0",
            "LSMinimumSystemVersion": "15.0",
            "NSHighResolutionCapable": true,
            bottleKey: item.bottle.path.path,
            programKey: item.app.executable,
            iconKey: "\(DockIcon.style) \((item.app.iconStyle ?? .icon).value) \(item.app.icon ?? "")",
        ]
        // macOS treats each wrapper as its own app for privacy prompts, and denies the microphone outright
        // to an app without a usage string, so wrappers carry OverPass's.
        for (key, value) in Bundle.main.infoDictionary ?? [:] where key.hasSuffix("UsageDescription") || key == "NSBonjourServices" {
            plist[key] = value
        }

        let unchanged = (try? String(contentsOf: script, encoding: .utf8)) == scriptText
            && NSDictionary(contentsOf: contents.appendingPathComponent("Info.plist")) == plist as NSDictionary
        if unchanged && fm.fileExists(atPath: icns.path) { return }

        try fm.createDirectory(at: script.deletingLastPathComponent(), withIntermediateDirectories: true)
        try fm.createDirectory(at: icns.deletingLastPathComponent(), withIntermediateDirectories: true)
        try scriptText.write(to: script, atomically: true, encoding: .utf8)
        try fm.setAttributes([.posixPermissions: 0o755], ofItemAtPath: script.path)
        try (plist as NSDictionary).write(to: contents.appendingPathComponent("Info.plist"))

        if let ico = WindowsIcons.icoFile(for: item.app, in: item.bottle), let image = NSImage(contentsOf: ico) {
            writeICNS(image, style: item.app.iconStyle ?? .icon, to: icns)
        }
        // Finder, the Dock and Launchpad cache bundle info; tell them it changed.
        LSRegisterURL(app as CFURL, true)
        NSWorkspace.shared.noteFileSystemChanged(app.path)
    }

    /// ICNS needs fixed sizes; Windows icons top out at 256, so larger sizes are upscaled from the best frame.
    private static func writeICNS(_ image: NSImage, style: ArtStyle, to url: URL) {
        let sizes = [16, 32, 64, 128, 256, 512, 1024]
        guard let dest = CGImageDestinationCreateWithURL(url as CFURL, UTType.icns.identifier as CFString, sizes.count, nil) else { return }
        for size in sizes {
            if let icon = DockIcon.render(image, style: style, size: size) { CGImageDestinationAddImage(dest, icon, nil) }
        }
        CGImageDestinationFinalize(dest)
    }

    private static func sanitize(_ name: String) -> String {
        let cleaned = name.replacingOccurrences(of: "/", with: "-").replacingOccurrences(of: ":", with: "-")
            .trimmingCharacters(in: .whitespaces.union(CharacterSet(charactersIn: ".")))
        return cleaned.isEmpty ? "Windows App" : cleaned
    }

    private static func shellQuote(_ s: String) -> String {
        "'" + s.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }
}

/// A Windows icon as a Mac app icon. macOS 26 sets icons that aren't a rounded square on a light plate, where
/// white and light icons vanish, so wrappers bring their own plate: the same backdrop as a generated cover.
enum DockIcon {
    /// Bumped when the drawing changes, so existing wrappers are redrawn.
    static let style = 3

    /// The icon on its plate, drawn on Apple's icon grid: an 824-point rounded square in a 1024-point canvas. A
    /// picture (no transparency) fills the plate at the style's `picture` size instead of sitting on it. `plate` is
    /// the backdrop when it's already drawn (`plate(for:style:size:)`), so a preview can move the icon quickly.
    static func render(_ image: NSImage, style: ArtStyle, size: Int, plate: CGImage? = nil) -> CGImage? {
        let scale = CGFloat(size) / 1024
        let plateRect = CGRect(x: 100, y: 100, width: 824, height: 824).applying(CGAffineTransform(scaleX: scale, y: scale))
        guard let probe = image.cgImage(forProposedRect: nil, context: nil, hints: nil) else { return nil }
        // Top-down, as the editor shows it; flipped into the context's bottom-up space below.
        var drawRect: CGRect
        if ArtStyle.isPicture(probe) {
            drawRect = style.pictureRect(image.size, in: plateRect)
        } else {
            let side = (plateRect.width * CGFloat(style.scale) / 100).rounded()
            drawRect = CGRect(x: plateRect.midX - side / 2 + plateRect.width * CGFloat(style.x) / 100,
                              y: plateRect.midY - side / 2 + plateRect.height * CGFloat(style.y) / 100, width: side, height: side)
        }
        drawRect.origin.y = CGFloat(size) - drawRect.maxY
        var proposed = CGRect(origin: .zero, size: drawRect.size)
        guard let source = image.cgImage(forProposedRect: &proposed, context: nil, hints: nil),
              let plate = plate ?? Self.plate(for: image, style: style, size: size),
              let ctx = CGContext(data: nil, width: size, height: size, bitsPerComponent: 8, bytesPerRow: 0,
                                  space: CGColorSpace(name: CGColorSpace.sRGB)!,
                                  bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue) else { return nil }
        ctx.interpolationQuality = .high
        ctx.saveGState()
        ctx.addPath(CGPath(roundedRect: plateRect, cornerWidth: 185 * scale, cornerHeight: 185 * scale, transform: nil))
        ctx.clip()
        ctx.draw(plate, in: plateRect)
        // The same soft shadow as the icon on a generated cover.
        ctx.setShadow(offset: CGSize(width: 0, height: -12 * scale), blur: 24 * scale,
                      color: CGColor(gray: 0, alpha: 0.35))
        ctx.draw(source, in: drawRect)
        ctx.restoreGState()
        return ctx.makeImage()
    }

    /// The backdrop of a `size`-pixel icon, which only the style's base and frost change.
    static func plate(for image: NSImage, style: ArtStyle, size: Int) -> CGImage? {
        let side = 824 * CGFloat(size) / 1024
        return style.background(for: image, size: CGSize(width: side, height: side))
    }
}

// MARK: - Launch mode

/// `OverPass --launch <bottle> <program> [arguments…]`: what app wrappers run. Replaces this process with Wine, so the
/// wrapper's Dock icon belongs to the running game, and never starts the UI.
enum WrapperLaunch {
    /// Starts OverPass hidden if it isn't running, so the report hotkey and the crash report work for a game started
    /// from its wrapper. `open` outlives this process, which becomes Wine.
    private static func startInBackground() {
        let id = "no.arctim.overpass"
        guard NSRunningApplication.runningApplications(withBundleIdentifier: id).allSatisfy({ $0.processIdentifier == getpid() }) else { return }
        let open = Process()
        open.executableURL = URL(fileURLWithPath: "/usr/bin/open")
        open.arguments = ["-g", "-j", "-b", id]
        try? open.run()
    }

    /// A game started from its wrapper opens behind whatever is frontmost: since macOS 14 only the frontmost app can
    /// hand over, and that's Finder or the Dock, which know nothing of Wine. The wrapper starts this helper, which
    /// `--launch` outlives by becoming Wine. Only a launch the person just asked for does this, and only until
    /// they've moved on to something else.
    private static func startBringForward() {
        guard let path = Bundle.main.executablePath else { return }
        let helper = Process()
        helper.executableURL = URL(fileURLWithPath: path)
        helper.arguments = ["--bring-forward"]
        try? helper.run()
    }

    /// Waits for the new Wine program's window and opens its bundle, which LaunchServices brings to the front for
    /// an app in the background too. NSWorkspace's lists only update while the run loop runs.
    @MainActor
    static func bringForward() -> Never {
        guard let root = BottleManager.findWine() else { exit(1) }
        let isWine = WineProcess.runsWine(under: root)
        func wineWindows() -> [NSRunningApplication] {
            NSWorkspace.shared.runningApplications.filter {
                $0.activationPolicy == .regular && $0.executableURL.map { isWine($0.path) } == true
                    && !BottleManager.wineServices.contains(($0.localizedName ?? "").lowercased() + ".exe")
            }
        }
        let before = Set(wineWindows().map(\.processIdentifier))
        let front = NSWorkspace.shared.frontmostApplication?.processIdentifier
        let start = Date.now
        while Date.now.timeIntervalSince(start) < 120 {
            RunLoop.current.run(until: .now + 0.5)
            let now = NSWorkspace.shared.frontmostApplication
            if now?.processIdentifier != front && now?.bundleIdentifier != "com.apple.finder" { exit(0) }
            guard let game = wineWindows().first(where: { !before.contains($0.processIdentifier) }) else { continue }
            if let bundle = game.bundleURL, !game.isTerminated { NSWorkspace.shared.open(bundle) } else { game.activate() }
            exit(0)
        }
        exit(0)
    }

    @MainActor
    static func run(bottlePath: String, program: String, arguments: [String]) -> Never {
        AppWrappers.syncAllowed = false
        let manager = BottleManager()
        let bottle = BottleManager.loadBottle(at: URL(fileURLWithPath: bottlePath))
        do {
            let process = try manager.exeProcess(program, in: bottle, arguments: arguments)
            guard let exe = process.executableURL else { throw WineError.noWineInstallation }
            StartedTitles.add(bottle.path.path + "|" + ([program] + arguments).joined(separator: "|"))
            startInBackground()
            startBringForward()
            if let cwd = process.currentDirectoryURL { FileManager.default.changeCurrentDirectoryPath(cwd.path) }
            let argv = ([exe.path] + (process.arguments ?? [])).map { strdup($0) } + [nil]
            let envp = (process.environment ?? [:]).map { strdup("\($0.key)=\($0.value)") } + [nil]
            execve(exe.path, argv, envp)
            throw POSIXError(POSIXErrorCode(rawValue: errno) ?? .ENOENT)
        } catch {
            _ = NSApplication.shared
            let alert = NSAlert()
            alert.messageText = "Couldn't open \(URL(fileURLWithPath: program).deletingPathExtension().lastPathComponent)"
            alert.informativeText = error.localizedDescription
            alert.runModal()
            exit(1)
        }
    }
}
